'use strict';
const assert = require('assert');
const B = require('../src/shared/blocking');
const adult = new Set(['example-adult.com']);
assert.strictEqual(B.reason('www.pornhub.com', adult, true, true), 'adult');
assert.strictEqual(B.reason('cdn.example-adult.com', adult, true, true), 'adult');
assert.strictEqual(B.reason('old.reddit.com', adult, true, true), 'social');
assert.strictEqual(B.reason('old.reddit.com', adult, true, false), null);
assert.strictEqual(B.reason('www.netflix.com', adult, true, true), null);
assert.strictEqual(B.reason('com', adult, true, true), null);
assert.ok(B.safeSearch('https://www.google.com/search?q=cats').includes('safe=active'));
assert.strictEqual(B.safeSearch('https://www.google.com/search?q=cats&safe=active'), null);
assert.ok(B.safeSearch('https://www.google.co.uk/search?q=cats&safe=off').includes('safe=active'));
assert.ok(B.safeSearch('https://www.bing.com/search?q=cats').includes('adlt=strict'));
assert.ok(B.safeSearch('https://duckduckgo.com/?q=cats&kp=-2').includes('kp=1'));
assert.strictEqual(B.safeSearch('https://www.google.com/maps'), null);
assert.strictEqual(B.toUrl('netflix.com'), 'https://netflix.com');
assert.strictEqual(B.toUrl('kids movies', 'bing'), 'https://www.bing.com/search?adlt=strict&q=kids%20movies');
assert.strictEqual(B.toUrl('https://a.b/c'), 'https://a.b/c');
console.log('blocking: passed');
